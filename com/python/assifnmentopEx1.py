# Program for swapping two numbers
a = input("Enter a value of a:")
b = input("Enter a value of b:")
print("="*20)
print("\tOriginal value of a:{}".format(a))
print("\tOriginal value of b:{}".format(b))
print("="*20)
# Swapping logic
a,b = b,a
print("\tAfter swapping value of a:{}".format(a))
print("\tAfter swapping value of b:{}".format(b))
print("="*20)